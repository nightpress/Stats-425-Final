"""Generate a synthetic episode library for offline pipeline validation.

This writes episode directories whose ``action_log.jsonl`` files have the same
shape Incalmo emits, so the full extract -> analyze pipeline can be exercised -
and the statistical analysis previewed - without spending any API budget. It is
a test fixture and a demo, NOT a model of attacker behavior; real conclusions
come from real episodes generated by :mod:`research.run_sweep`.

    PYTHONPATH=. python3 -m research.synthesize research/out/demo_library
"""

from __future__ import annotations

import argparse
import json
import os
import random
from datetime import datetime, timedelta
from config.attacker_config import StealthConfig
from pathlib import Path


def _line(ts: datetime, type_: str, action_name: str, results: dict | None = None,
          params: dict | None = None) -> str:
    rec = {"type": type_, "timestamp": ts.isoformat(), "action_name": action_name}
    if params is not None:
        rec["action_params"] = params
    if results is not None:
        rec["action_results"] = results
    return json.dumps(rec)


def _attack_episode(rng: random.Random, n_hosts: int, include_exfil: bool = True) -> tuple[list[str], int]:
    """Return (jsonl lines, n_exfil) for one synthetic attacker episode.

    include_exfil=False truncates at credential-access (mimicking a safety-bounded
    LLM attacker), which is both quieter and never reaches exfiltration."""
    t = datetime(2025, 1, 1, 12, 0, 0)
    lines: list[str] = []
    step = lambda lo, hi: timedelta(seconds=rng.uniform(lo, hi))

    # recon
    for _ in range(rng.randint(1, 3)):
        t += step(2, 10)
        lines.append(_line(t, "LowLevelAction", "nmap",
                           {"HostsDiscovered": {"subnet_ip_mask": "10.0.0.0/24",
                                                "host_ips": [f"10.0.0.{i}" for i in range(n_hosts)]}}))
    n_exfil = 0
    # per-host compromise chain, with randomized aggressiveness
    for h in range(n_hosts):
        host = f"10.0.0.{h}"
        t += step(5, 60)
        lines.append(_line(t, "LowLevelAction", "exploit",
                           {"InfectedNewHost": {"new_agent": {"host": host}}}))
        if rng.random() < 0.6:
            t += step(2, 20)
            lines.append(_line(t, "LowLevelAction", "harvest",
                               {"SSHCredentialFound": {"agent": {"host": host}}}))
        for _ in range(rng.randint(1, 3)):
            t += step(2, 15)
            lines.append(_line(t, "LowLevelAction", "ls",
                               {"FilesFound": {"agent": {"host": host}}}))
        # exfil, preceded by the high-level action that names the target host
        if include_exfil:
            for _ in range(rng.randint(1, 4)):
                t += step(3, 30)
                lines.append(_line(t, "HighLevelAction", "ExfiltrateData",
                                   params={"target_host": host}))
                lines.append(_line(t, "LowLevelAction", "exfil",
                                   {"ExfiltratedData": {"file": f"data_{host}_{n_exfil}.json"}}))
                n_exfil += 1
    return lines, n_exfil


def _benign_episode(rng: random.Random) -> list[str]:
    """Low-severity background noise only - should rarely trip a sane threshold."""
    t = datetime(2025, 1, 1, 12, 0, 0)
    lines: list[str] = []
    for _ in range(rng.randint(5, 15)):
        t += timedelta(seconds=rng.uniform(20, 180))
        host = f"10.0.0.{rng.randint(0, 5)}"
        signal = rng.choice(["BashOutputEvent", "FilesFound", "HostsDiscovered"])
        if signal == "HostsDiscovered":
            payload = {"subnet_ip_mask": "10.0.0.0/24", "host_ips": [host]}
        else:
            payload = {"agent": {"host": host}}
        lines.append(_line(t, "LowLevelAction", "noise", {signal: payload}))
    return lines


def _write_episode(path: str, lines: list[str], attacker_model: str, env: str,
                   n_exfil: int, benign: bool) -> None:
    os.makedirs(path, exist_ok=True)
    with open(os.path.join(path, "action_log.jsonl"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    results = {
        "scenario": {"attacker": {"name": attacker_model, "llm": attacker_model,
                                  "abstraction": "incalmo"}, "environment": env},
        "data_exfiltrated": [{"name": f"f{i}", "time_exfiltrated": 0} for i in range(n_exfil)],
        "flags_captured": [], "execution_time": 0,
    }
    with open(os.path.join(path, "results.json"), "w", encoding="utf-8") as fh:
        json.dump(results, fh)


def make_library(out_dir: str, n_scripted: int = 12, n_llm: int = 12,
                 n_benign: int = 12, seed: int = 0) -> str:
    """Emit an autonomy-labeled synthetic library for validating the pipeline:
    scripted (loud, full kill chain incl. exfil) vs llm (truncated at
    credential-access, quieter) vs benign. Labels/schemas match the extractor;
    this is a FIXTURE, not a result."""
    rng = random.Random(seed)
    os.makedirs(out_dir, exist_ok=True)
    for i in range(n_scripted):  # loud, many hosts, exfiltrates -> easily detected
        lines, n_exfil = _attack_episode(rng, n_hosts=rng.randint(4, 7), include_exfil=True)
        _write_episode(os.path.join(out_dir, f"scripted-bfs__equifax_large__rep{i:03d}"),
                       lines, "scripted-bfs", "equifax_large", n_exfil, benign=False)
    for i in range(n_llm):  # truncated at cred-access (safety-bounded), quieter
        lines, n_exfil = _attack_episode(rng, n_hosts=rng.randint(1, 2), include_exfil=False)
        _write_episode(os.path.join(out_dir, f"llm-haiku__equifax_large__rep{i:03d}"),
                       lines, "llm-haiku", "equifax_large", n_exfil, benign=False)
    for i in range(n_benign):
        lines = _benign_episode(rng)
        _write_episode(os.path.join(out_dir, f"benign__equifax_large__rep{i:03d}"),
                       lines, "benign", "equifax_large", 0, benign=True)
    print(f"synthesized {n_scripted} scripted + {n_llm} llm + {n_benign} benign -> {out_dir}")
    return out_dir

def write_e3_fixture(
    path,
    lines,
    attacker_model,
    environment,
    n_exfil,
    stealth_config
):
    config = StealthConfig.model_validate(stealth_config)

    _write_episode(
        str(path),
        lines,
        attacker_model,
        environment,
        n_exfil,
        benign=False
    )

    metadata = {
        "experiment": "E3",
        "synthetic": True,
        "stealth": config.enabled,
        "stealth_config": config.model_dump()
    }

    with (Path(path) / "e3_config.json").open(
        "w", encoding="utf-8"
    ) as f:
        json.dump(metadata, f, indent=2)

def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("out_dir")
    p.add_argument("--scripted", type=int, default=12)
    p.add_argument("--llm", type=int, default=12)
    p.add_argument("--benign", type=int, default=12)
    p.add_argument("--seed", type=int, default=0)
    args = p.parse_args()
    make_library(args.out_dir, args.scripted, args.llm, args.benign, args.seed)


if __name__ == "__main__":
    main()
